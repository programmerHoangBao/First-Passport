-- ============================================================
-- ENUM TYPES (GENDER, STATUS, RESULT, ROLE)
-- ============================================================
-- Vì Oracle không có kiểu ENUM, ta dùng VARCHAR2 với constraint CHECK
-- Bạn có thể chỉnh sửa giá trị phù hợp với enum thực tế trong code

-- GENDER_TYPE: MALE, FEMALE
-- STATUS_TYPE: PENDING, VERIFIED, REJECTED
-- RESULT_TYPE: APPROVED, REJECTED
-- ROLE_TYPE: XT, XD, LT, GS
-- ============================================================


-- ============================================================
-- TABLE: USERS
-- ============================================================
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255 CHAR) NOT NULL,
    ROLE VARCHAR2(20 CHAR) CHECK (ROLE IN ('XT','XD','LT','GS')),
    FULL_NAME VARCHAR2(255 CHAR)
);

-- ============================================================
-- TABLE: RESIDENT_DATA
-- ============================================================
CREATE TABLE RESIDENT_DATA (
    IDENTITY_NUMBER VARCHAR2(12 CHAR) PRIMARY KEY,
    FULL_NAME VARCHAR2(255 CHAR),
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR2(10 CHAR) CHECK (GENDER IN ('MALE','FEMALE')),
    ADDRESS VARCHAR2(255 CHAR),
    PHONE VARCHAR2(10 CHAR) NOT NULL,
    EMAIL VARCHAR2(255 CHAR)
);

-- ============================================================
-- TABLE: FORM_REGISTRATION
-- ============================================================
CREATE TABLE FORM_REGISTRATION (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    IDENTITY_NUMBER VARCHAR2(12 CHAR) NOT NULL,
    FULL_NAME VARCHAR2(255 CHAR),
    ADDRESS VARCHAR2(255 CHAR),
    GENDER VARCHAR2(10 CHAR) CHECK (GENDER IN ('MALE','FEMALE')),
    PHONE VARCHAR2(10 CHAR) NOT NULL,
    EMAIL VARCHAR2(255 CHAR),
    CREATED_AT TIMESTAMP,
    STATUS VARCHAR2(20 CHAR) CHECK (STATUS IN ('PENDING','VERIFIED','REJECTED')),
    CONSTRAINT FK_REGISTRATION_RESIDENT FOREIGN KEY (IDENTITY_NUMBER)
        REFERENCES RESIDENT_DATA(IDENTITY_NUMBER)
);

-- ============================================================
-- TABLE: APPROVAL_DATA
-- ============================================================
CREATE TABLE APPROVAL_DATA (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FORM_ID NUMBER NOT NULL,
    RESULT VARCHAR2(20 CHAR) CHECK (RESULT IN ('APPROVED','REJECTED')),
    APPROVED_AT TIMESTAMP,
    APPROVER_USER_ID NUMBER,
    CREATED_BY NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_APPROVAL_FORM FOREIGN KEY (FORM_ID)
        REFERENCES FORM_REGISTRATION(ID),
    CONSTRAINT FK_APPROVAL_APPROVER FOREIGN KEY (APPROVER_USER_ID)
        REFERENCES USERS(ID),
    CONSTRAINT FK_APPROVAL_CREATOR FOREIGN KEY (CREATED_BY)
        REFERENCES USERS(ID)
);

-- ============================================================
-- TABLE: PASSPORTS
-- ============================================================
CREATE TABLE PASSPORTS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    IDENTITY_NUMBER VARCHAR2(12 CHAR) NOT NULL,
    APPROVAL_ID NUMBER NOT NULL,
    FULL_NAME VARCHAR2(255 CHAR),
    ADDRESS VARCHAR2(255 CHAR),
    GENDER VARCHAR2(10 CHAR) CHECK (GENDER IN ('MALE','FEMALE')),
    PHONE VARCHAR2(10 CHAR) NOT NULL,
    EMAIL VARCHAR2(255 CHAR),
    CREATED_AT TIMESTAMP,
    CREATED_BY NUMBER NOT NULL,

    CONSTRAINT FK_PASSPORT_RESIDENT FOREIGN KEY (IDENTITY_NUMBER)
        REFERENCES RESIDENT_DATA(IDENTITY_NUMBER),
    CONSTRAINT FK_PASSPORT_APPROVAL FOREIGN KEY (APPROVAL_ID)
        REFERENCES APPROVAL_DATA(ID),
    CONSTRAINT FK_PASSPORT_CREATOR FOREIGN KEY (CREATED_BY)
        REFERENCES USERS(ID)
);

-- ============================================================
-- TABLE: LOGS
-- ============================================================
CREATE TABLE LOGS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ACTOR VARCHAR2(50 CHAR),
    ROLE VARCHAR2(20 CHAR) CHECK (ROLE IN ('XT','XD','LT','GS')),
    ACTION VARCHAR2(255 CHAR),
    EVENT_TIME TIMESTAMP DEFAULT SYSTIMESTAMP,
    POLICY_NAME VARCHAR2(100),
    OBJECT_NAME VARCHAR2(50),
    SQL_TEXT CLOB
);

-- ============================================================
-- INDEXES (tùy chọn, giúp tối ưu truy vấn)
-- ============================================================
CREATE INDEX IDX_FORM_RESIDENT ON FORM_REGISTRATION (IDENTITY_NUMBER);
CREATE INDEX IDX_APPROVAL_FORM ON APPROVAL_DATA (FORM_ID);
CREATE INDEX IDX_PASSPORT_APPROVAL ON PASSPORTS (APPROVAL_ID);
CREATE INDEX IDX_PASSPORT_RESIDENT ON PASSPORTS (IDENTITY_NUMBER);
CREATE INDEX IDX_LOG_USER ON LOGS (ACTOR);

