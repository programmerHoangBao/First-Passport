ALTER SYSTEM SET AUDIT_TRAIL=DB, EXTENDED SCOPE=SPFILE;
SHUTDOWN IMMEDIATE;
STARTUP;

AUDIT SELECT, INSERT, UPDATE, DELETE ON group5_user.FORM_REGISTRATION BY ACCESS;
AUDIT SELECT, INSERT, UPDATE, DELETE ON group5_user.APPROVAL_DATA BY ACCESS;
AUDIT SELECT, INSERT, UPDATE, DELETE ON group5_user.USERS BY ACCESS;
AUDIT SELECT, INSERT, UPDATE, DELETE ON group5_user.RESIDENT_DATA BY ACCESS;

